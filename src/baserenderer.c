int initialize_window_context() {
    if (!glfwInit()) {
        printf("Failed to initialize GLFW\n");
        return -1;
    }

    glfwWindowHint(GLFW_CONTEXT_VERSION_MAJOR, 3);
    glfwWindowHint(GLFW_CONTEXT_VERSION_MINOR, 3);
    glfwWindowHint(GLFW_OPENGL_PROFILE, GLFW_OPENGL_CORE_PROFILE);

    window = glfwCreateWindow(DEFAULT_WINDOW_WIDTH, DEFAULT_WINDOW_HEIGHT, WINDOW_NAME, NULL, NULL);
    if (!window) {
        printf("Failed to create GLFW window\n");
        glfwTerminate();
        return -1;
    }

    glfwMakeContextCurrent(window);

    glewExperimental = true;
    if (glewInit() != GLEW_OK) {
        glfwDestroyWindow(window);
        glfwTerminate();
        printf("Failed to initialize GLEW\n");
        return -1;
    }

    return 0;
}

GLuint vertex_array_object, vertex_buffer_object, element_buffer_object;

int setup_vertex_buffers() {

    glGenVertexArrays(1, &vertex_array_object);
    glGenBuffers(1, &vertex_buffer_object);
    glGenBuffers(1, &element_buffer_object);

    glBindVertexArray(vertex_array_object);

    glBindBuffer(GL_ARRAY_BUFFER, vertex_buffer_object);
    glBufferData(GL_ARRAY_BUFFER, sizeof(screen_quad), screen_quad, GL_STATIC_DRAW);

    glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, element_buffer_object);
    glBufferData(GL_ELEMENT_ARRAY_BUFFER, sizeof(quad_indices), quad_indices, GL_STATIC_DRAW);

    return 0;
}

GLuint compile_shader(const char* source, GLenum type) {
    GLuint shader = glCreateShader(type);
    glShaderSource(shader, 1, (const char**)&source, NULL);

    glCompileShader(shader);

    GLint success;
    char info_log[SHADER_COMPILATION_LOG_SIZE];
    glGetShaderiv(shader, GL_COMPILE_STATUS, &success);

    if (!success) {
        glGetShaderInfoLog(shader, SHADER_COMPILATION_LOG_SIZE, NULL, info_log);
        printf("Error while compiling shader:\n%s\n", info_log);
        glDeleteShader(shader);
        return 0;
    }

    return shader;
}

GLuint link_shaders() {
    
    GLuint vertex_shader = compile_shader(vertex_src, GL_VERTEX_SHADER);
    GLuint fragment_shader = compile_shader(fragment_src, GL_FRAGMENT_SHADER);

    if (!vertex_shader || !fragment_shader) {
        return 0;
    }

    GLuint program = glCreateProgram();
    glAttachShader(program, vertex_shader);
    glAttachShader(program, fragment_shader);
    glLinkProgram(program);

    GLint success;
    char info_log[SHADER_COMPILATION_LOG_SIZE];
    glGetProgramiv(program, GL_LINK_STATUS, &success);
    if (!success) {
        glGetProgramInfoLog(program, 512, NULL, info_log);
        printf("Error while linking occurred:\n%s\n", info_log);
        glDeleteProgram(program);
        program = 0;
    }

    glDeleteShader(vertex_shader);
    glDeleteShader(fragment_shader);

    return program;
}

void update_chunk_texture(texture_instance chunk_texture_instance, int32_t index) {
    glActiveTexture(GL_TEXTURE0 + chunk_texture_instance.binding_index);
    glBindTexture(GL_TEXTURE_2D_ARRAY, chunk_texture_instance.descriptor);

    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);

    glTexSubImage3D(
        GL_TEXTURE_2D_ARRAY,
        0,
        0, 0, index,
        CHUNK_SIZE,
        CHUNK_SIZE,
        1,
        GL_RED_INTEGER,
        GL_UNSIGNED_SHORT,
        &chunk_array[CHUNK_SIZE * CHUNK_SIZE * index]
    );
}

float viewport_start_chunk_x;
float viewport_end_chunk_x;
float viewport_start_chunk_y;
float viewport_end_chunk_y;

void update_viewport() {
    viewport_start_chunk_x = FLOOR_DIV((int32_t)floorf(camera_position_x - 0.5 * aspect_ratio * camera_zoom), CHUNK_SIZE);
    viewport_end_chunk_x   = FLOOR_DIV((int32_t)floorf(camera_position_x + 0.5 * aspect_ratio * camera_zoom), CHUNK_SIZE);
    viewport_start_chunk_y = FLOOR_DIV((int32_t)floorf(camera_position_y - 0.5 * camera_zoom), CHUNK_SIZE);
    viewport_end_chunk_y   = FLOOR_DIV((int32_t)floorf(camera_position_y + 0.5 * camera_zoom), CHUNK_SIZE);
}